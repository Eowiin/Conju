function formatRule(rule, lang) {
  const texts = RULE_TEXT[lang] || RULE_TEXT.fr;
  const text = texts[rule.id] || RULE_TEXT.fr[rule.id] || "";
  return text.replace(/\{(\w+)\}/g, (m, key) => (key in rule.p ? rule.p[key] : m));
}

// Rule text for one exercise. The imperative has one rule per person.
function getRule(verb, tense, pronoun, lang) {
  const entry = CONJ.verbs[verb];
  if (!entry || !entry.rules[tense]) return "";
  const k = CONJ.persons.indexOf(pronoun);
  return entry.rules[tense]
    .filter(rule => rule.pers === undefined || rule.pers === k)
    .map(rule => formatRule(rule, lang))
    .join(" ");
}
